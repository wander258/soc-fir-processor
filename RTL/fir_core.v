// ============================================================
// fir_core.v —— FIR 数据通路内核【接口契约冻结版 v1：只有端口，没有实现】
//
// ⚠️ 这不是一个能用的模块，它是一份【用代码写成的契约】。
//
// 为什么要有它：
//   如果不先把端口定死，A 和 B 会各自按自己的想象写，
//   等合并的时候才发现端口名/位宽对不上，两边都要返工。
//   有了这个空壳：
//     · A 可以直接拿它当起点，把内部实现补全
//     · B 可以直接例化它，先把自己的 AXI 外壳跑通（空壳输出恒 0，不影响握手验证）
//     两个人【从第一天起就能并行】，谁都不用等谁。
//
// ============================================================
// 使用规则（重要）
// ============================================================
//   1. A 负责把下面的实现补全，但【端口一个都不许改】。
//   2. 任何人要改端口 = 改契约 = 必须先在群里发起、三人同意、
//      把 docs/阶段1-接口契约（冻结版）.md 升到 v2，再通知所有人。
//   3. 代码评审时只检查一件事：你的实现和契约文件一不一致。
//
// 行为约定（详见 docs/阶段1-接口契约（冻结版）.md 契约 A）：
//   A1  吞吐 1 sample/cycle：en 连续拉高时 dout_v 每拍都有效
//   A2  流水线延迟固定 5 拍
//   A3  dout_v 与 dout 同拍对齐
//   A4  flush 拉高一拍：延迟线与流水线清零，dout_v 保持 0，系数保留
//   A5  coef_we 拉高一拍：把 coef_din 写入 h[coef_idx]
//   A6  定点：乘积 Q2.30 精确，累加 40bit 不溢出，输出右移 15 位回 Q1.15 并饱和
// ============================================================
`timescale 1ns/1ps

module fir_core #(
    parameter DW   = 16,        // 数据位宽 Q1.15
    parameter CW   = 16,        // 系数位宽 Q1.15
    parameter AW   = 40,        // 累加器位宽（下限 38，取 40）
    parameter NTAP = 81         // 抽头数
)(
    input  wire                    clk,
    input  wire                    rst_n,
    input  wire                    flush,       // 清空延迟线与流水线（系数保留）
    input  wire                    en,          // 每拍处理一个样本
    input  wire signed [DW-1:0]    din,
    output wire signed [DW-1:0]    dout,
    output wire                    dout_v,      // dout 有效标志（与 dout 同拍）
    input  wire [$clog2(NTAP)-1:0] coef_idx,    // 系数写口：第几个
    input  wire signed [CW-1:0]    coef_din,    // 系数写口：值
    input  wire                    coef_we      // 系数写口：写使能（一拍）
);

    // ============================================================
    // ↓↓↓ 以下为占位实现，A 请用真正的数据通路替换掉 ↓↓↓
    //     （81 级延迟链 + 81 个并行乘法 + 7 级加法树 + 5 级流水）
    // ============================================================
    assign dout   = {DW{1'b0}};
    assign dout_v = 1'b0;

endmodule
