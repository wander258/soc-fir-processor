// ============================================================
// 实验 05：81 阶 FIR 滤波器（全并行，1 sample/cycle）
//
// 这就是赛题第一项要求：81 阶、系数 16bit 定点、数据 16bit、≥1 sample/cycle。
// 架构和实验 04 完全一样，只是 NTAP 从 9 变成 81。
//
// ⚠️ 这是"功能正确"版本：81 项加法串成一条组合链，仿真能跑对，
//    但在真实 FPGA 上跑 50MHz 大概率时序不收敛。要过时序必须把
//    最后那串累加改成流水线加法树（见 README 第 3 节）。
//
// 定点约定（必须和 gen_fir_vectors.py 里的黄金模型完全一致）：
//     x, h 都是 Q1.15：真实值 = 整数 / 2^15
//     乘积 = X*H / 2^30
//     累加 S = Σ X[k]*H[k]
//     输出回到 Q1.15：y = S / 2^15 = S >>> 15
//
// 时序：en 拉高时每拍吃进一个样本，dout_v 高表示 dout 有效。
//       输出相对输入有 1 拍流水线延迟。
//
// 系数由 gen_fir_vectors.py 生成到 coeffs.vh，不要在 Verilog 里手写系数。
// ============================================================
`timescale 1ns/1ps

module fir #(
    parameter DW   = 16,        // 数据位宽
    parameter CW   = 16,        // 系数位宽（Q1.15）
    parameter AW   = 40,        // 累加器位宽（81 阶必须 >= 39，取 40）
    parameter NTAP = 81         // 抽头数（赛题要求 81）
)(
    input  wire                 clk,
    input  wire                 rst_n,
    input  wire                 en,                     // 每拍处理一个样本
    input  wire signed [DW-1:0] din,
    output reg  signed [DW-1:0] dout,
    output reg                  dout_v                  // 输出有效标志
);

    // ---------------------------------------------------------
    // 1. 系数：由 coeffs.vh 提供 localparam H0..H(NTAP-1) 和 assign
    // ---------------------------------------------------------
    wire signed [CW-1:0] h [0:NTAP-1];
`include "coeffs.vh"

    // ---------------------------------------------------------
    // 2. 样本延迟线：x[0] 是最新样本，x[k] = x[n-k]
    //    （就是实验 02 的那条延迟线）
    // ---------------------------------------------------------
    reg signed [DW-1:0] x [0:NTAP-1];

    // ---------------------------------------------------------
    // 3. 并行乘法：NTAP 个 16x16 有符号乘法器
    //    赛题决赛要求做对称优化：h[k] == h[NTAP-1-k]，可以先把
    //    x[k] + x[NTAP-1-k] 加起来再乘，乘法器数量从 81 降到 41。
    // ---------------------------------------------------------
    wire signed [DW+CW-1:0] p [0:NTAP-1];
    genvar g;
    generate
        for (g = 0; g < NTAP; g = g + 1) begin : g_mul
            assign p[g] = x[g] * h[g];
        end
    endgenerate

    // ---------------------------------------------------------
    // 4. 加法树（这里先写成组合逻辑的累加，最简单直白）
    //    每一项都要符号扩展到 AW 位，否则负数求和会出错
    // ---------------------------------------------------------
    reg signed [AW-1:0] sum;
    integer k;
    always @(*) begin
        sum = {AW{1'b0}};
        for (k = 0; k < NTAP; k = k + 1)
            sum = sum + {{(AW-DW-CW){p[k][DW+CW-1]}}, p[k]};
    end

    // ---------------------------------------------------------
    // 5. 截位回 Q1.15：取 sum 的 [SHIFT+DW-1 : SHIFT] 这一段
    //    SHIFT = CW-1 = 15，即右移 15 位
    // ---------------------------------------------------------
    localparam SHIFT = CW - 1;

    wire signed [DW-1:0] y_trunc = sum[SHIFT+DW-1 : SHIFT];

    // ---------------------------------------------------------
    // 6. 饱和处理：如果截位丢掉的不是纯符号扩展，说明溢出，钳到最大/最小
    //    不做饱和的话，大信号会被"回绕"成反相的尖峰，这是滤波器的大忌
    // ---------------------------------------------------------
    wire overflow = (sum[AW-1 : SHIFT+DW] != {{(AW-SHIFT-DW){sum[SHIFT+DW-1]}}});

    wire signed [DW-1:0] y_sat = overflow
                               ? (sum[AW-1] ? {1'b1, {DW-1{1'b0}}}      // 负溢出 -> 最小
                                            : {1'b0, {DW-1{1'b1}}})     // 正溢出 -> 最大
                               : y_trunc;

    // ---------------------------------------------------------
    // 7. 输出寄存
    // ---------------------------------------------------------
    integer i;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (i = 0; i < NTAP; i = i + 1)
                x[i] <= {DW{1'b0}};
            dout   <= {DW{1'b0}};
            dout_v <= 1'b0;
        end
        else if (en) begin
            for (i = NTAP-1; i > 0; i = i - 1)
                x[i] <= x[i-1];
            x[0]   <= din;
            dout   <= y_sat;        // 注意：这里 sum 用的还是移位前的 x[]，
            dout_v <= 1'b1;         // 这正是滤波需要的 x[n-k]
        end
        else begin
            dout_v <= 1'b0;
        end
    end

endmodule
